#include "main.h"

/**
 * _isupper - Checks if a character is lowercase
 * @c: Character to check
 *
 * Return: 1 if lowercase, 0 otherwise
 */

void more_numbers(void)
{
char alphabet;

for (alphabet = 'a'; alphabet <= 'z'; alphabet++)
{
_putchar(alphabet);
}

_putchar('\n');
return;
}
